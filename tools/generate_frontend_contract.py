"""Generate the frontend TypeScript contract from backend constants."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from backend.app.shared import contract

OUTPUT = REPO_ROOT / "frontend" / "domain" / "contract.generated.ts"


def _array(name: str, values: tuple[str, ...], type_name: str) -> str:
    rendered = json.dumps(list(values), ensure_ascii=False)
    return f"export const {name} = {rendered} as const;\nexport type {type_name} = (typeof {name})[number];\n"


def render() -> str:
    lines = [
        "// Generated by tools/generate_frontend_contract.py. Do not edit.",
        "",
        f"export const TRANSLATION_TEXTS_MAX = {contract.TRANSLATION_TEXTS_MAX};",
        f"export const COMPOSE_TRANSLATION_MAX_CHARS = {contract.COMPOSE_TRANSLATION_MAX_CHARS};",
        "",
        f"export const PORTRAIT_BATCH_MAX = {contract.PORTRAIT_BATCH_MAX};",
        f"export const PORTRAIT_EXPORT_MAX = {contract.PORTRAIT_EXPORT_MAX};",
        f"export const PORTRAIT_TAG_NAME_MAX = {contract.PORTRAIT_TAG_NAME_MAX};",
        f"export const PORTRAIT_TAG_DESCRIPTION_MAX = {contract.PORTRAIT_TAG_DESCRIPTION_MAX};",
        f"export const PORTRAIT_LOST_NOTE_MAX = {contract.PORTRAIT_LOST_NOTE_MAX};",
        "",
        f"export const EXPERIMENT_MAX_VARIANTS = {contract.EXPERIMENT_MAX_VARIANTS};",
        f"export const EXPERIMENT_MAX_STEPS = {contract.EXPERIMENT_MAX_STEPS};",
        f"export const LLM_MAX_LEVEL = {contract.LLM_MAX_LEVEL};",
        "",
        _array("OUTBOX_STATUSES", contract.OUTBOX_STATUSES, "OutboxStatus"),
        _array("REPLY_STATES", contract.REPLY_STATES, "ReplyState"),
        _array("PORTRAIT_STAGES", contract.PORTRAIT_STAGES, "PortraitStage"),
        _array("LOST_REASONS", contract.LOST_REASONS, "LostReason"),
        _array("STEP_MODES", contract.STEP_MODES, "StepMode"),
        _array("SESSION_TYPES", contract.SESSION_TYPES, "SessionType"),
        _array("PINNED_KINDS", contract.PINNED_KINDS, "PinnedKind"),
    ]
    return "\n".join(lines)


def write() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail when the generated file is stale")
    args = parser.parse_args()

    expected = render()
    if args.check:
        actual = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else None
        if actual != expected:
            print(f"{OUTPUT} is stale; run python tools/generate_frontend_contract.py", file=sys.stderr)
            return 1
        return 0

    write()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
